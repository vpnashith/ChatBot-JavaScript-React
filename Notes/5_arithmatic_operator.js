let num = 5

console.log(num + 10) // 15 (addition)
console.log(num - 2) // 3 (subtraction)
console.log(num * 3) // 15 (multiplication)
console.log(num / 2) // 2.5 (division)
console.log(num % 3) // 2 (modulus - remainder of division)
console.log(num ** 2) // 25 (exponentiation - num raised to the power of 2)

console.log(num++) // 5 (post-increment - returns num then increments)
console.log(num) // 6 (num is now incremented)      

console.log(++num) // 7 (pre-increment - increments num then returns it)
console.log(num) // 7 (num is now incremented)  

console.log(num--) // 7 (post-decrement - returns num then decrements)
console.log(num) // 6 (num is now decremented)

console.log(--num) // 5 (pre-decrement - decrements num then returns it)
console.log(num) // 5 (num is now decremented)

