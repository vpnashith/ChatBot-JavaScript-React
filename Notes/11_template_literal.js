let n1 = 10
let n2 = 20
let sum = n1 + n2
console.log(`The sum of ${n1} and ${n2} is ${sum}`) // The sum of 10 and 20 is 30
// Template literals allow for embedding expressions and variables directly within a string using `${...}` syntax.

let customer_name = "Alice"
let greeting = `Hello, ${customer_name}!`
console.log(greeting) // Hello, Alice!

// Template literals can also span multiple lines
